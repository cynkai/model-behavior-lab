"""Synthetic demo study. Every value is drawn at random; nothing is an observation.

The demo exists to show the workflow and exercise every code path (format
failures, errors, missing runs, an excluded run, unrecognized labels). The
per-condition parameters are random draws that do not encode any belief about
how a real service behaves, and the study is marked ``demo: true`` so every
output carries a SYNTHETIC banner.
"""

from __future__ import annotations

import math
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

import yaml

from mblab.plan import generate_plan
from mblab.records import build_record
from mblab.schema import (
    DateScoring,
    ExperimentDefinition,
    NumericScoring,
    RunRecord,
    SequenceScoring,
)
from mblab.study import (
    DEFINITION_FILE,
    PLAN_FILE,
    RECORDS_FILE,
    Study,
    StudyError,
    save_plan,
    template_text,
    write_jsonl,
)

DEMO_BANNER = (
    "SYNTHETIC DEMO DATA — generated by `mblab demo`. Values are random and say nothing "
    "about any real model or service."
)
DEMO_START = datetime(2026, 1, 5, 9, 0, tzinfo=timezone(timedelta(hours=9)))
_HEADER = (
    "# SYNTHETIC DEMO STUDY — generated by `mblab demo`.\n"
    "# Every record in this directory is random. None of it was observed.\n"
)


def _wrong_answer(definition: ExperimentDefinition, task_id: str, rng: random.Random) -> str:
    rule = definition.task(task_id).scoring
    if isinstance(rule, NumericScoring):
        delta = rng.choice([-3, -2, -1, 1, 2, 10])
        if isinstance(rule.expected, list):
            wrong = [rule.expected[0] + delta, *rule.expected[1:]]
            return "(" + ", ".join(f"{v:g}" for v in wrong) + ")"
        return f"{rule.expected + delta:g}"
    if isinstance(rule, DateScoring):
        return (rule.expected + timedelta(days=rng.choice([-1, 1, 2]))).isoformat()
    if isinstance(rule, SequenceScoring):
        return ", ".join(reversed(rule.expected))
    return "unknown"


def create_demo_study(root: Path, seed: int = 7, missing: int = 4, force: bool = False) -> Study:
    if root.exists() and any(root.iterdir()) and not force:
        raise StudyError(f"{root} is not empty; choose a new directory or pass --force")
    root.mkdir(parents=True, exist_ok=True)

    data = yaml.safe_load(template_text())
    data["demo"] = True
    data["experiment_id"] = f"demo-{data['experiment_id']}"
    data["title"] = f"[SYNTHETIC DEMO] {data['title']}"
    definition = ExperimentDefinition.model_validate(data)
    (root / DEFINITION_FILE).write_text(
        _HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    plan = generate_plan(definition, now=DEMO_START)
    save_plan(plan, root / PLAN_FILE)

    rng = random.Random(seed)
    labels = [o.label for o in definition.selection_options]
    params = {
        c.id: {
            "p_correct": rng.uniform(0.25, 0.95),
            "latency_median": math.exp(rng.uniform(math.log(3), math.log(300))),
            "p_thinking": rng.random(),
            "p_label": rng.uniform(0.3, 0.9),
        }
        for c in definition.conditions
    }
    run_ids = [r.run_id for r in plan.runs]
    missing_ids = set(rng.sample(run_ids, min(missing, len(run_ids))))
    deviation_id = rng.choice([rid for rid in run_ids if rid not in missing_ids])
    defaults = {
        c.id: ("none" if "none" in c.allowed_values else c.allowed_values[0])
        for c in definition.confounders
    }
    defaults.update(
        {
            k: v
            for k, v in {
                "memory": "disabled",
                "custom_instructions": "inactive",
                "network": "wifi",
            }.items()
            if k in defaults
        }
    )

    records: list[RunRecord] = []
    clock = DEMO_START
    for run in sorted(plan.runs, key=lambda r: r.sequence):
        clock += timedelta(seconds=round(rng.uniform(120, 360)))
        if run.run_id in missing_ids:
            continue
        p = params[run.condition_id]
        task = definition.task(run.task_id)
        status = "error" if rng.random() < 0.03 else "completed"
        latency = round(p["latency_median"] * math.exp(rng.gauss(0, 0.3)), 1)
        fields: dict = {
            "client_version": "0.0.0-demo",
            "timestamp": clock,
            "data_origin": "synthetic",
            "response_status": status,
            "latency_seconds": latency,
            "latency_method": "manual_stopwatch",
            "recorded_by": "mblab-demo",
            "recorded_at": clock + timedelta(seconds=round(latency) + 30),
            "notes": "Synthetic demo record.",
            "confounders": {
                k: ("unknown" if rng.random() < 0.03 else v) for k, v in defaults.items()
            },
        }
        if status == "completed":
            answer = (
                task.reference_answer
                if rng.random() < p["p_correct"]
                else _wrong_answer(definition, task.id, rng)
            )
            lines = [
                "[SYNTHETIC DEMO RESPONSE — not produced by any model]",
                f"Task {task.id}, condition {run.condition_id}, repetition {run.repetition}.",
            ]
            if rng.random() > 0.05:
                lines.append(f"ANSWER: {answer}")
            fields["response_text"] = "\n".join(lines)
            roll = rng.random()
            if roll < 0.05:
                fields["observed_model_label"] = "Synthetic label"
            elif roll < p["p_label"]:
                fields["observed_model_label"] = rng.choice(labels)
            if fields.get("observed_model_label"):
                fields["observed_label_location"] = "synthetic"
            if rng.random() < p["p_thinking"]:
                seconds = max(1, round(latency * rng.uniform(0.4, 0.9)))
                fields["thinking_indicator"] = "shown"
                fields["thinking_text"] = f"Thought for {seconds}s"
            else:
                fields["thinking_indicator"] = "not_shown"
        if run.run_id == deviation_id:
            fields["protocol_deviation"] = "SYNTHETIC example of an excluded run."
        records.append(build_record(run, definition, plan, **fields))

    write_jsonl(root / RECORDS_FILE, records)
    return Study.load(root)

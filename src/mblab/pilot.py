"""Pilot studies: a short, separate run of a study before real collection.

A pilot answers practical questions the definition must settle in advance —
above all, what text the client displays next to a response for each option,
so ``observed_label_aliases`` can be filled in *before* the main study collects
data. Deciding aliases from the main study's own data would be a post-hoc change.

The pilot is its own study directory with its own ``experiment_id`` (suffix
``-pilot``) and ``pilot: true``. Its run ids start with ``pilot:`` and its seed is the
main seed + 1, so its order differs from the main study's. Its records are real
observations, but they are never part of the experiment's results: importing them
(or a filled-in pilot CSV) into the main study is refused, because their run ids are
not in the main plan.
"""

from __future__ import annotations

from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from mblab.plan import generate_plan
from mblab.study import (
    DEFINITION_FILE,
    PLAN_FILE,
    Study,
    StudyError,
    load_definition,
    parse_definition,
    save_plan,
)

PILOT_BANNER = (
    "PILOT DATA — collected to check the protocol and the labels the client displays. "
    "Not part of the experiment's results; never copy these records into the main study."
)
PILOT_SUFFIX = "-pilot"
_HEADER = (
    "# PILOT STUDY — generated by `mblab pilot` from {source}.\n"
    "# Use it to check the protocol and to see which labels the client displays.\n"
    "# Its records are never part of the main study's results.\n"
)


def create_pilot_study(
    main: Path, out: Path | None = None, repetitions: int = 1, force: bool = False
) -> tuple[Study, Path]:
    """Copy the main study's definition into a new pilot study directory and plan it."""
    definition = load_definition(main / DEFINITION_FILE)
    if definition.pilot or definition.demo:
        raise StudyError(f"{main} is a pilot or demo study; make a pilot from the main study")
    target = out or main.with_name(main.name + PILOT_SUFFIX)
    if target.exists() and any(target.iterdir()) and not force:
        raise StudyError(f"{target} is not empty; choose a new directory or pass --force")

    data = yaml.safe_load((main / DEFINITION_FILE).read_text(encoding="utf-8"))
    # Shorten the id, never the suffix: a 64-character id would otherwise lose
    # "-pilot" and the pilot would carry the main study's id.
    pilot_id = definition.experiment_id[: 64 - len(PILOT_SUFFIX)] + PILOT_SUFFIX
    if pilot_id == definition.experiment_id:
        raise StudyError(f"cannot derive a pilot experiment_id distinct from {pilot_id!r}")
    data["experiment_id"] = pilot_id
    # A different seed, so rehearsing the pilot does not rehearse the main study's order.
    data["randomization"] = {
        **(data.get("randomization") or {}),
        "seed": definition.randomization.seed + 1,
    }
    data["title"] = f"[PILOT] {definition.title}"
    data["repetitions"] = repetitions
    data["pilot"] = True
    text = _HEADER.format(source=main / DEFINITION_FILE) + yaml.safe_dump(
        data, sort_keys=False, allow_unicode=True
    )
    pilot_definition = parse_definition(text, str(target / DEFINITION_FILE))
    target.mkdir(parents=True, exist_ok=True)
    (target / DEFINITION_FILE).write_text(text, encoding="utf-8")
    save_plan(generate_plan(pilot_definition), target / PLAN_FILE)
    return Study.load(target), target


@dataclass
class LabelText:
    """One distinct displayed label, verbatim, and where it was seen."""

    text: str
    runs: int = 0
    conditions: dict[str, int] = field(default_factory=dict)
    locations: dict[str, int] = field(default_factory=dict)
    matches: list[str] = field(default_factory=list)


def displayed_labels(study: Study) -> tuple[list[LabelText], int]:
    """Every distinct displayed label (verbatim) and the number of runs with none.

    ``matches`` lists the option ids whose pre-registered label or alias the text
    matches; an empty list means the text matches no option yet.
    """
    by_text: dict[str, LabelText] = {}
    conditions: dict[str, defaultdict[str, int]] = {}
    locations: dict[str, defaultdict[str, int]] = {}
    none = 0
    for rec in study.records:
        label = rec.observed_model_label
        if not label:
            none += 1
            continue
        item = by_text.setdefault(label, LabelText(label))
        item.runs += 1
        conditions.setdefault(label, defaultdict(int))[rec.condition_id] += 1
        where = rec.observed_label_location or "not recorded"
        locations.setdefault(label, defaultdict(int))[where] += 1
    for label, item in by_text.items():
        item.conditions = dict(sorted(conditions[label].items()))
        item.locations = dict(sorted(locations[label].items()))
        item.matches = [o.id for o in study.definition.selection_options if o.matches_label(label)]
    return sorted(by_text.values(), key=lambda i: (-i.runs, i.text)), none
